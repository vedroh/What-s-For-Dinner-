import pandas as pd
from scipy.sparse import csr_matrix
import implicit

df = pd.read_csv("PolsovatelyTest2.csv", index_col=0)
df = df.groupby(df.index).max()

user_item = csr_matrix(df.values)

model = implicit.als.AlternatingLeastSquares(factors=10, iterations=15)
model.fit(user_item)

user_id = 1
recs = model.recommend(user_id, user_item[user_id], N=5, filter_already_liked_items=True)

for idx in recs[0]:
    print(df.columns[idx])